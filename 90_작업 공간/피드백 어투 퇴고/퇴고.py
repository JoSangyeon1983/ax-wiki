if not ORIGINAL.exists():
    ORIGINAL.write_bytes(TARGET.read_bytes())
before = ORIGINAL.read_text(encoding='utf-8-sig')
after = before
for old, new in EDITS:
    assert after.count(old) == 1, old
    after = after.replace(old, new, 1)

# 발표자, 발표 내용, 첨부 표와 기존 URL은 편집 범위에서 제외함.
for pattern in [r'^\[발표자:.*$', r'^\|.*$', r'발표 내용\n\n([^\n]+)', r'\]\(([^)]+)\)']:
    assert re.findall(pattern, before, re.M) == re.findall(pattern, after, re.M), pattern
assert before.count('내용 기입') == after.count('내용 기입') == 1
assert len(re.findall(r'^\[발표자:', after, re.M)) == 15

front = '''---
title: "피드백"
type: article
created: "2026-10-27"
updated: "2026-10-27"
status: draft
sources: []
target_folder: 03_Articles
---

<!-- 사용자 제공 문서의 어투만 편집했으며, 별도 근거 자료를 사용하지 않아 sources는 빈 목록으로 유지함. -->

'''
stage = front + after.rstrip() + '\n'
if '--publish' in sys.argv:
    assert TARGET.read_bytes() == ORIGINAL.read_bytes(), '원본이 변경되어 반영을 중단함.'
